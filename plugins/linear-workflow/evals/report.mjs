#!/usr/bin/env node
// Writes evals/RESULTS.md from the newest `claude plugin eval` run (or the aggregate-result.json given).

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const evalsDir = dirname(fileURLToPath(import.meta.url))
const resultsDir = join(evalsDir, 'results')

function newestAggregate() {
  if (!existsSync(resultsDir)) return null
  const runs = readdirSync(resultsDir).filter(d => existsSync(join(resultsDir, d, 'aggregate-result.json'))).sort()
  return runs.length ? join(resultsDir, runs[runs.length - 1], 'aggregate-result.json') : null
}

const source = process.argv[2] ?? newestAggregate()
if (!source || !existsSync(source)) {
  console.error('✗ No eval results found. Run `npm run eval` (or `claude plugin eval .`) first.')
  process.exit(1)
}

const data = JSON.parse(readFileSync(source, 'utf8'))
if (data.partial) {
  console.error('✗ That run was partial (stopped early); not reporting it.')
  process.exit(1)
}

const description = c => {
  const yaml = join(c.dir ?? join(evalsDir, c.name), 'case.yaml')
  const m = existsSync(yaml) ? /^description:\s*"?(.*?)"?\s*$/m.exec(readFileSync(yaml, 'utf8')) : null
  return m?.[1] ?? ''
}
const usd = n => `$${n.toFixed(2)}`
const pct = n => `${Math.round(n * 100)}%`

const plugin = data.suite.plugins?.[0] ?? { name: 'plugin', version: '?' }
const rows = []
const failures = []
for (const c of data.cases) {
  const runs = c.arms.with ?? []
  const cost = runs.reduce((sum, r) => sum + (r.costUsd ?? 0) + (r.judgeCostUsd ?? 0), 0)
  const turns = runs.length ? runs.reduce((sum, r) => sum + (r.turns ?? 0), 0) / runs.length : 0
  const passed = runs.filter(r => r.passed).length
  rows.push(`| \`${c.name}\` | ${description(c)} | ${passed}/${runs.length} | ${c.aggregates.score.toFixed(2)} | ${turns.toFixed(1)} | ${usd(cost)} |`)
  runs.forEach((r, n) => {
    if (r.error) failures.push(`- \`${c.name}\` run ${n + 1}: error: ${String(r.error).split('\n')[0]}`)
    for (const g of r.graders ?? []) if (g.scored && !g.passed) failures.push(`- \`${c.name}\` run ${n + 1}: **${g.name}**: ${g.explanation}`)
  })
}

const a = data.aggregates
const md = `# Eval results

Generated by \`evals/report.mjs\` from the run of ${data.startedAt.slice(0, 10)}. Do not edit by hand.

| | |
| --- | --- |
| Plugin | ${plugin.name} ${plugin.version} |
| Claude Code | ${data.claudeVersion} |
| Cases passed | ${a.casesPassed}/${a.casesTotal} (overall score ${a.overallScore.toFixed(2)}, pass rate ${pct(a.overallPassRate)}) |
| Runs per case | ${data.cases[0]?.runsPerCase ?? '?'} |
| Duration | ${data.durationSeconds}s |
| Cost | ${usd(data.costUsd)} |

| Case | What it checks | Runs passed | Score | Avg turns | Cost |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

${failures.length ? `## Failed graders\n\n${failures.join('\n')}\n` : 'Every grader passed on every run.\n'}
Each case runs a skill against canned CLI answers (see the Development section of the plugin README)
and grades what Claude did: which commands it ran and what it told the user.
`

writeFileSync(join(evalsDir, 'RESULTS.md'), md)
console.log(`✓ evals/RESULTS.md: ${a.casesPassed}/${a.casesTotal} case(s) passed, ${data.cases.length} reported, from ${source}`)
